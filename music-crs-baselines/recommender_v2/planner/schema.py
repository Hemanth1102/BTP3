from dataclasses import dataclass, field, fields
from typing import List, Optional


# Fields older planner versions generated but nothing in the pipeline used.
# Plans cached by those versions still load: these keys are dropped on read.
LEGACY_FIELDS = (
    "mood_phrases",
    "sonic_descriptors",
    "lyrical_themes",
    "year_terms",
    "negative_constraints",
    "mentioned_entities",
    "rejected_track_ids",
)


@dataclass
class QueryState:
    """
    Structured representation of the user's current request: the contract
    between the planner and the retrievers / feature builder.

    Every field below is read by at least one component (see the comments);
    a field nothing reads is not generated, because each output token costs
    planner time.
    """

    # ---- set by the pipeline, never generated by the LLM ----
    raw_query: str = ""                 # the user's message (lookup text fallback)
    anchor_track_ids: List[str] = field(default_factory=list)   # tracks played so far

    # ---- search text ----
    bm25_query: str = ""                # -> BM25
    semantic_query: str = ""            # -> BGE and the other text retrievers

    # ---- explicit entities ----
    artist_names: List[str] = field(default_factory=list)   # -> artist_lookup, artist_match
    album_names: List[str] = field(default_factory=list)    # -> album_lookup, album_match
    track_titles: List[str] = field(default_factory=list)   # -> title_lookup, title_match

    # ---- constraints ----
    genre_tags: List[str] = field(default_factory=list)     # -> genre_match
    min_year: Optional[int] = None                           # -> year_in_range
    max_year: Optional[int] = None
    rejected_artists: List[str] = field(default_factory=list)  # -> lookups skip them; rejected_artist_match

    # ---- request type (ranker features) ----
    intent: str = "discovery"
    need_personalization: bool = True
    need_new_artist: bool = False
    need_new_track: bool = False
    planner_confidence: float = 1.0

    def to_dict(self):
        return {f.name: getattr(self, f.name) for f in fields(self)}

    @classmethod
    def from_dict(cls, data):
        """Build from a (possibly older) cached plan, ignoring retired fields."""
        known = {f.name for f in fields(cls)}
        return cls(**{k: v for k, v in dict(data).items() if k in known})


# Fields the LLM must generate (everything except the pipeline-set ones).
LLM_FIELDS = tuple(f.name for f in fields(QueryState)
                   if f.name not in ("raw_query", "anchor_track_ids"))
