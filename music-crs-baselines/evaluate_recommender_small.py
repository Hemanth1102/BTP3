import math
from typing import Dict, List, Tuple

from datasets import load_dataset

from recommender_v2.retrievers import (
    BM25Retriever,
    CFBPRRetriever,
)
from recommender_v2 import RecommenderV2


DATASET_NAME = "talkpl-ai/TalkPlayData-Challenge-Dataset"

ITEM_DATASET = "talkpl-ai/TalkPlayData-Challenge-Track-Metadata"

TRACK_EMBEDDING_DATASET = (
    "talkpl-ai/TalkPlayData-Challenge-Track-Embeddings"
)

USER_EMBEDDING_DATASET = (
    "talkpl-ai/TalkPlayData-Challenge-User-Embeddings"
)


def ndcg_at_k(predictions: List[str], ground_truth: str, k: int) -> float:
    """
    Calculate nDCG@k for a single example.

    The challenge has one ground-truth track per turn.
    Relevance is 1 if the predicted track matches the target.
    """

    predictions = predictions[:k]

    for rank, track_id in enumerate(predictions, start=1):
        if track_id == ground_truth:
            dcg = 1.0 / math.log2(rank + 1)

            # With exactly one relevant item, IDCG is 1.
            return dcg

    return 0.0


def build_retrievers():
    print("Loading BM25...")

    bm25 = BM25Retriever(
        dataset_name=ITEM_DATASET,
        split_types=["all_tracks"],
        corpus_types=[
            "track_name",
            "artist_name",
            "album_name",
            "release_date",
        ],
        cache_dir="./cache",
    )

    print("Loading CF-BPR...")

    cf_bpr = CFBPRRetriever(
        user_dataset_name=USER_EMBEDDING_DATASET,
        track_dataset_name=TRACK_EMBEDDING_DATASET,
        user_split="train",
        track_split="all_tracks",
    )

    recommender = RecommenderV2(
        bm25=bm25,
        cf_bpr=cf_bpr,
        candidate_k=100,
        final_k=20,
    )

    return bm25, cf_bpr, recommender


def extract_user_turns(session: Dict) -> List[Tuple[int, str, str]]:
    """
    Extract:

        turn_number
        user query up to that turn
        ground-truth music track

    from one training session.
    """

    conversations = session["conversations"]

    results = []

    current_history = []

    # Track ID generated by the system at each turn.
    music_by_turn = {}

    for message in conversations:

        role = message["role"]
        turn_number = message["turn_number"]
        content = message["content"]

        if role == "user":
            current_history.append(
                {
                    "role": "user",
                    "content": content,
                }
            )

        elif role == "music":
            # The "music" message content is the ground-truth track ID.
            music_by_turn[turn_number] = content

            current_history.append(
                {
                    "role": "music",
                    "content": content,
                }
            )

        elif role == "assistant":
            current_history.append(
                {
                    "role": "assistant",
                    "content": content,
                }

            )

        # Evaluate immediately after we have seen the user query
        # and its corresponding music recommendation.
        if (
            role == "music"
            and turn_number in music_by_turn
        ):

            # Reconstruct the conversation exactly as text expected
            # by the baseline retrieval module.
            retrieval_input = "\n".join(
                f"{msg['role']}: {msg['content']}"
                for msg in current_history
                if msg["role"] != "music"
            )

            results.append(
                (
                    turn_number,
                    retrieval_input,
                    music_by_turn[turn_number],
                )
            )

    return results


def evaluate_session(
    session: Dict,
    bm25,
    cf_bpr,
    recommender,
):
    """
    Evaluate all available turns in one session.
    """

    user_id = session["user_id"]

    turn_data = extract_user_turns(session)

    print("\n" + "=" * 70)
    print("SESSION:", session["session_id"])
    print("USER:", user_id)
    print("=" * 70)

    session_scores = {
        "bm25": [],
        "cf_bpr": [],
        "hybrid": [],
    }

    for turn_number, query, ground_truth in turn_data:

        bm25_results = bm25.retrieve(
            query=query,
            topk=20,
            user_id=user_id,
        )

        cf_results = cf_bpr.retrieve(
            query=query,
            topk=20,
            user_id=user_id,
        )

        hybrid_predictions = recommender.recommend(
            query=query,
            user_id=user_id,
        )

        bm25_predictions = [
            result.track_id
            for result in bm25_results
        ]

        cf_predictions = [
            result.track_id
            for result in cf_results
        ]

        bm25_ndcg = ndcg_at_k(
            bm25_predictions,
            ground_truth,
            20,
        )

        cf_ndcg = ndcg_at_k(
            cf_predictions,
            ground_truth,
            20,
        )

        hybrid_ndcg = ndcg_at_k(
            hybrid_predictions,
            ground_truth,
            20,
        )

        bm25_hit = ground_truth in bm25_predictions
        cf_hit = ground_truth in cf_predictions
        hybrid_hit = ground_truth in hybrid_predictions

        session_scores["bm25"].append(bm25_ndcg)
        session_scores["cf_bpr"].append(cf_ndcg)
        session_scores["hybrid"].append(hybrid_ndcg)

        print(f"\nTurn {turn_number}")
        print(f"Ground truth: {ground_truth}")

        print(
            f"BM25:    "
            f"{'HIT' if bm25_hit else 'MISS'} "
            f"nDCG@20={bm25_ndcg:.4f}"
        )

        print(
            f"CF-BPR:  "
            f"{'HIT' if cf_hit else 'MISS'} "
            f"nDCG@20={cf_ndcg:.4f}"
        )

        print(
            f"Hybrid:  "
            f"{'HIT' if hybrid_hit else 'MISS'} "
            f"nDCG@20={hybrid_ndcg:.4f}"
        )

    return session_scores


def main():

    # ---------------------------------------------------------
    # Load data
    # ---------------------------------------------------------

    print("Loading challenge dataset...")

    dataset = load_dataset(DATASET_NAME)

    train = dataset["train"]

    # ---------------------------------------------------------
    # Choose only 5 sessions.
    # ---------------------------------------------------------

    sessions = train.select(range(5))

    # ---------------------------------------------------------
    # Build recommender
    # ---------------------------------------------------------

    bm25, cf_bpr, recommender = build_retrievers()

    all_scores = {
        "bm25": [],
        "cf_bpr": [],
        "hybrid": [],
    }

    # ---------------------------------------------------------
    # Evaluate
    # ---------------------------------------------------------

    for session in sessions:

        scores = evaluate_session(
            session,
            bm25,
            cf_bpr,
            recommender,
        )

        for key in all_scores:
            all_scores[key].extend(scores[key])

    # ---------------------------------------------------------
    # Final summary
    # ---------------------------------------------------------

    print("\n" + "=" * 70)
    print("FINAL RESULTS")
    print("=" * 70)

    for method, scores in all_scores.items():

        if scores:
            mean_score = sum(scores) / len(scores)
        else:
            mean_score = 0.0

        print(
            f"{method:10s} "
            f"nDCG@20 = {mean_score:.4f}"
        )


if __name__ == "__main__":
    main()